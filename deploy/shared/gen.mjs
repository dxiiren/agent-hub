// Generates compose.yaml, Caddyfile, .env.template and env/<dev>.env.template for the given developers.
// Usage: node deploy/shared/gen.mjs dev1 dev2 [dev3 ...]   (names: lowercase letters, digits, dash)
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const devs = process.argv.slice(2);
if (devs.length < 1 || devs.length > 250 || devs.some((d) => !/^[a-z][a-z0-9-]*$/.test(d)) || new Set(devs).size !== devs.length) {
  console.error('usage: node gen.mjs <dev> [<dev> ...]  (unique, ^[a-z][a-z0-9-]*$)');
  process.exit(2);
}
const dir = dirname(fileURLToPath(import.meta.url));
const up = (d) => d.toUpperCase().replace(/-/g, '_');

const compose = [
  '# GENERATED by gen.mjs: edit the dev list and regenerate, do not hand-edit.',
  '# One Paseo container per developer (own volume, own CLI logins, own network) behind one login proxy.',
  'name: agenthub-shared',
  'services:',
  ...devs.flatMap((d, i) => [
    `  ${d}:`,
    ...(i === 0 ? ['    build: .'] : []),
    '    image: agenthub-paseo:0.15.0',
    `    container_name: agenthub-shared-${d}`,
    '    restart: unless-stopped',
    `    env_file: [env/${d}.env]`,
    '    extra_hosts: ["host.docker.internal:host-gateway"]',
    `    volumes: ["${d}_home:/home/paseo"]`,
    `    networks: [net_${d.replace(/-/g, '_')}]`,
  ]),
  '  proxy:',
  '    image: caddy:2',
  '    container_name: agenthub-shared-proxy',
  '    restart: unless-stopped',
  '    ports: ["${HUB_BIND:-127.0.0.1}:${HUB_PROXY_PORT:-18080}:8080"]',
  '    env_file: [.env]',
  '    volumes: ["./Caddyfile:/etc/caddy/Caddyfile:ro"]',
  `    networks: [${devs.map((d) => 'net_' + d.replace(/-/g, '_')).join(', ')}]`,
  'volumes:',
  ...devs.map((d) => `  ${d}_home: {name: agenthub-shared_${d}_home}`),
  'networks:',
  ...devs.map((d, i) => `  net_${d.replace(/-/g, '_')}: {name: agenthub-shared-net-${d}, ipam: {config: [{subnet: 10.79.${i + 1}.0/24}]}}`),
  '',
].join('\n');

const caddy = [
  '# GENERATED by gen.mjs. Host name routes to the dev; basic auth is the only barrier on the LAN side.',
  '{', '\tauto_https off', '\tadmin off', '}',
  ':8080 {',
  ...devs.flatMap((d) => [
    `\t@${d.replace(/-/g, '_')} host ${d}.{$HUB_DOMAIN:localhost}`,
    `\thandle @${d.replace(/-/g, '_')} {`,
    `\t\tbasic_auth {\n\t\t\t${d} {$HASH_${up(d)}}\n\t\t}`,
    `\t\treverse_proxy ${d}:6767`,
    '\t}',
  ]),
  '\thandle {', '\t\trespond "no such dev" 404', '\t}',
  '}', '',
].join('\n');

const proxyEnv = [
  '# Copy to .env (git-ignored). One bcrypt hash per dev from: docker run --rm caddy:2 caddy hash-password',
  '# Keep the hashes in SINGLE quotes: they contain $ characters.',
  '#HUB_BIND=127.0.0.1',
  '#HUB_PROXY_PORT=18080',
  '#HUB_DOMAIN=localhost',
  ...devs.map((d) => `HASH_${up(d)}=''`),
  '',
].join('\n');

const devEnv = (d) => [
  `# Copy to env/${d}.env (git-ignored). No provider credentials here: the dev logs in to Codex, Claude, Qoder and`,
  '# Qwen Code inside the container once (their logins live in the dev volume).',
  `HUB_DEV=${d}`,
  '# Office SGLang as an OpenCode provider: base URL ending in /v1 (empty = no office provider)',
  'HUB_OFFICE_URL=',
  'HUB_OFFICE_MODEL=Qwen3.8-27B',
  '# Usage telemetry to the usage stack (counts only; its collector drops logs and strips identity)',
  'OTEL_EXPORTER_OTLP_ENDPOINT=http://host.docker.internal:4317',
  'OTEL_EXPORTER_OTLP_PROTOCOL=grpc',
  `OTEL_RESOURCE_ATTRIBUTES=dev=${d}`,
  'CLAUDE_CODE_ENABLE_TELEMETRY=1',
  'OTEL_METRICS_EXPORTER=otlp',
  'OTEL_LOGS_EXPORTER=none',
  '',
].join('\n');

mkdirSync(join(dir, 'env'), { recursive: true });
writeFileSync(join(dir, 'compose.yaml'), compose);
writeFileSync(join(dir, 'Caddyfile'), caddy);
writeFileSync(join(dir, '.env.template'), proxyEnv);
for (const d of devs) writeFileSync(join(dir, 'env', `${d}.env.template`), devEnv(d));
console.log(`generated for ${devs.length} dev(s): ${devs.join(', ')}`);
